#define COLI_TARGET_PROFILE_ID_MACOS_ARM64_METAL_APPLE8_V1 {apple["profile_id"]}u
#define COLI_TARGET_PROFILE_ABI_APPLE8_V1 {apple["target_profile_abi"]}u
#define COLI_EXECUTION_LAYOUT_ABI_APPLE8_V1 {apple["execution_layout_abi"]}u
