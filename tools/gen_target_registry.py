#define COLI_TARGET_CLASS_APPLE8_METAL_V1 0x{apple["target_class"]:08x}u
#define COLI_LAYOUT_APPLE_MXFP4_TILE8X32_V1 0x{tile["id"]:04x}u

#define COLI_APPLE8_MXFP4_MATH_FORMAT 0x{tile["math_format"]:04x}u
#define COLI_APPLE8_MXFP4_SCALE_FORMAT 0x{tile["scale_format"]:04x}u
#define COLI_APPLE8_MXFP4_SCALE_BLOCK_ROWS {tile["scale_block_rows"]}u
