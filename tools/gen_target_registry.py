#define COLI_APPLE8_MXFP4_TILE_COLUMNS {tile["tile_columns"]}u
#define COLI_APPLE8_MXFP4_WEIGHT_ROW_BYTES {row_bytes}u
#define COLI_APPLE8_MXFP4_WEIGHT_BYTES {weight_bytes}u
#define COLI_APPLE8_MXFP4_SCALE_BYTES {scale_bytes}u
#define COLI_APPLE8_MXFP4_TILE_BYTES {tile["tile_bytes"]}u

#define COLI_APPLE8_TARGET_OS {apple["target_os"]}u
